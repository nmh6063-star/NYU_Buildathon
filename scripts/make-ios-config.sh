#!/usr/bin/env bash
# Writes ios/Droplet/Resources/Config.xcconfig (gitignored) for the Droplet app.
#
#   scripts/make-ios-config.sh
#       Local stack: reads API_URL and PUBLISHABLE_KEY (or ANON_KEY) from `supabase status -o env`.
#
#   SUPABASE_URL=https://<ref>.supabase.co SUPABASE_PUBLISHABLE_KEY=sb_publishable_... scripts/make-ios-config.sh
#       Remote project: uses the two environment variables as given.
#
# The key is written to the file only; it is never printed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/ios/Droplet/Resources/Config.xcconfig"

url="${SUPABASE_URL:-}"
key="${SUPABASE_PUBLISHABLE_KEY:-}"

if [[ -z "$url" || -z "$key" ]]; then
  if ! status="$(cd "$ROOT" && supabase status -o env 2>/dev/null)"; then
    echo "error: 'supabase status' failed. Start the local stack with 'supabase start'," >&2
    echo "       or set SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY." >&2
    exit 1
  fi
  # Lines look like: API_URL="http://127.0.0.1:54321"
  read_var() {
    printf '%s\n' "$status" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -n 1
  }
  url="$(read_var API_URL)"
  key="$(read_var PUBLISHABLE_KEY)"
  if [[ -z "$key" ]]; then
    key="$(read_var ANON_KEY)"
  fi
fi

if [[ -z "$url" || -z "$key" ]]; then
  echo "error: could not determine the Supabase URL and publishable key." >&2
  exit 1
fi

# xcconfig treats "//" as the start of a comment, so split the scheme separator with $().
xc_url="$(printf '%s' "$url" | sed 's#://#:/$()/#')"

mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
// Generated by scripts/make-ios-config.sh. Gitignored: do not commit.
SUPABASE_URL = $xc_url
SUPABASE_PUBLISHABLE_KEY = $key
EOF

echo "Wrote ios/Droplet/Resources/Config.xcconfig (SUPABASE_URL = $url)"
